import { writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const root = new URL('../../', import.meta.url);
const path = (relative) => fileURLToPath(new URL(relative, root));

/**
 * Write the MCP tools/list payload as a static module, so the Worker never converts schemas at
 * request time. The conversion is the one the MCP SDK applied: zod's Standard JSON Schema input
 * view (draft 2020-12) with `type: "object"` at the root.
 */
export async function generateToolList() {
  // Bundle the tool table to an ignored file so Node can import it; zod stays an external package.
  const bundled = path('dist/mcp-tools.mjs');
  await build({
    entryPoints: [path('src/server/mcp/tools.ts')],
    bundle: true,
    packages: 'external',
    platform: 'node',
    format: 'esm',
    outfile: bundled,
    logLevel: 'warning',
  });
  const { TOOLS } = await import(pathToFileURL(bundled).href + '?' + Date.now());
  const list = Object.entries(TOOLS).map(([name, tool]) => ({
    name,
    description: tool.description,
    inputSchema: {
      type: 'object',
      ...tool.schema['~standard'].jsonSchema.input({ target: 'draft-2020-12' }),
    },
    annotations: tool.annotations,
  }));
  await writeFile(
    path('src/server/mcp/tools.generated.ts'),
    '// Generated by src/tooling/mcp-tools.mjs from src/server/mcp/tools.ts during `npm run build`.\n' +
      '// Do not edit by hand. Committed so typecheck and Wrangler work before a build.\n' +
      `export const TOOL_LIST = ${JSON.stringify(list, null, 2)};\n`,
  );
}
