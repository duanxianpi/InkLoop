import { createHash } from 'node:crypto';
import { cp, readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const path = (...parts) => resolve(root, ...parts);
const text = (file) => readFile(file, 'utf8');
const json = async (file) => JSON.parse(await text(file));
const accepted = new Set([
  'MIT',
  'ISC',
  'BSD-2-Clause',
  'Apache-2.0',
  'Python-2.0',
  'CC0-1.0',
  '0BSD',
  'OFL-1.1',
  'SEE LICENSE IN LICENSE.md',
]);

/** Offline, deterministic inventory of installed locked production dependencies, including
 * transitives. Conservative: includes packages even when tree-shaking removes them from a bundle.
 * Build-only/dev dependencies are not redistributed by the application and are excluded. */
export async function thirdPartyNotices() {
  const lock = await json(path('package-lock.json'));
  const manifest = await json(path('package.json'));
  if (
    manifest.dependencies.tldraw !== '3.15.6' ||
    manifest.dependencies['@tldraw/assets'] !== '3.15.6'
  )
    throw new Error('Review tldraw licensing and vendored notices before changing its version');
  const sources = await json(path('third-party/upstream/sources.json'));
  const upstream = new Map();
  for (const source of sources) {
    const body = await readFile(path('third-party/upstream', source.file));
    if (createHash('sha256').update(body).digest('hex') !== source.sha256)
      throw new Error(`Upstream license text changed: ${source.file}`);
    upstream.set(source.file, body.toString('utf8'));
  }
  const supplement = (file) => {
    if (!upstream.has(file)) throw new Error(`Missing upstream license: ${file}`);
    return upstream.get(file);
  };
  const sections = [
    'InkLoop third-party notices\n\nGenerated by npm run licenses from package-lock.json and installed production packages.\n' +
      'InkLoop original code is MIT licensed; third-party software retains its own terms.\n' +
      'This conservative inventory includes transitive packages that may be removed by tree-shaking.\n' +
      'Upstream supplement provenance and SHA-256 hashes: third-party/upstream/sources.json.\n\n' +
      'InkLoop LICENSE\n\n' +
      (await text(path('LICENSE'))),
  ];
  for (const [directory, entry] of Object.entries(lock.packages).sort(([a], [b]) =>
    a.localeCompare(b, 'en'),
  )) {
    if (!directory || entry.dev) continue;
    let pkg;
    try {
      pkg = await json(path(directory, 'package.json'));
    } catch (error) {
      if (entry.optional && error.code === 'ENOENT') continue;
      throw error;
    }
    if (pkg.version !== entry.version)
      throw new Error(`Run npm ci: version mismatch for ${directory}`);
    if (!accepted.has(pkg.license))
      throw new Error(`Review license for ${pkg.name}: ${pkg.license}`);
    const files = (await readdir(path(directory)))
      .filter((name) => /^(licen[cs]e|copying|notice|copyright)([.\-_]|$)/i.test(name))
      .sort();
    const bodies = [];
    for (const file of files) {
      try {
        bodies.push(`${file}\n\n${await text(path(directory, file))}`);
      } catch (error) {
        if (error.code !== 'EISDIR') throw error;
      }
    }
    // Some published tldraw packages contain only a link to the changing main-branch license.
    // Preserve it, but also ship the complete text belonging to the pinned version.
    if (pkg.license === 'SEE LICENSE IN LICENSE.md') {
      if (
        ![
          'tldraw',
          '@tldraw/assets',
          '@tldraw/editor',
          '@tldraw/utils',
          '@tldraw/validate',
        ].includes(pkg.name) ||
        pkg.version !== '3.15.6'
      )
        throw new Error(`Review non-SPDX license: ${pkg.name}@${pkg.version}`);
      if (['tldraw', '@tldraw/assets', '@tldraw/editor'].includes(pkg.name))
        bodies.push(
          'Pinned tldraw 3.15.6 license (additional complete upstream text)\n\n' +
            supplement('tldraw-3.15.6-LICENSE.md'),
        );
    }
    if (!bodies.length && pkg.name.startsWith('@tiptap/') && pkg.version === '2.27.3')
      bodies.push(supplement('tiptap-2.27.3-LICENSE.md'));
    if (!bodies.length && pkg.name === 'react-remove-scroll-bar' && pkg.version === '2.3.8')
      bodies.push(supplement('react-remove-scroll-bar-LICENSE'));
    if (!bodies.length && pkg.name === 'mj-context-menu' && pkg.version === '0.6.1') {
      // The npm package declares Apache-2.0 but omits the text. Include the standard text from
      // MathJax, which depends on this package, and retain this package's published metadata.
      bodies.push(
        'Apache-2.0 text (from mathjax-full/LICENSE)\n\n' +
          (await text(path('node_modules/mathjax-full/LICENSE'))),
      );
    }
    if (!bodies.length) throw new Error(`Missing license text for ${pkg.name}@${pkg.version}`);
    // Apache's generic license text may not name the actual copyright owner; preserve the
    // attribution headers from the installed sources used by the math renderer as well.
    const attributionFile = {
      'mathjax-full': 'ts/mathjax.ts',
      mhchemparser: 'dist/mhchemParser.js',
    }[pkg.name];
    if (attributionFile) {
      const source = await text(path(directory, attributionFile));
      const header = source.match(/\/\*[\s\S]*?Copyright[\s\S]*?\*\//)?.[0];
      if (!header) throw new Error(`Review missing attribution: ${pkg.name}/${attributionFile}`);
      bodies.push(`Attribution from ${attributionFile}\n\n${header}`);
    }
    sections.push(
      '='.repeat(72) +
        `\n${pkg.name}@${pkg.version}\nPath: ${directory}\nDeclared license: ${pkg.license}\n` +
        `Repository: ${typeof pkg.repository === 'string' ? pkg.repository : (pkg.repository?.url ?? pkg.homepage ?? '')}\n` +
        (pkg.author
          ? `Author: ${typeof pkg.author === 'string' ? pkg.author : pkg.author.name}\n`
          : '') +
        '\n' +
        bodies.join('\n\n'),
    );
  }
  for (const file of ['tldraw-3.15.6-TRADEMARKS.md', 'IBM-Plex-OFL.txt', 'Shantell-Sans-OFL.txt'])
    sections.push(
      '='.repeat(72) + `\nAdditional tldraw assets / terms: ${file}\n\n` + supplement(file),
    );
  return sections.join('\n\n') + '\n';
}

export async function checkNotices() {
  const expected = await thirdPartyNotices();
  if ((await text(path('THIRD_PARTY_NOTICES.txt'))) !== expected)
    throw new Error('Third-party notices are stale; run npm run licenses and review the changes');
  return expected;
}

export async function publishNotices() {
  await checkNotices();
  // Rail.tsx imports the combined notices with Vite's ?url, so they are distributed under
  // a content-hashed /assets URL. A new license inventory cannot reuse a cached old URL.
  // Replace the assets package's link-only placeholder with the full pinned license.
  await cp(
    path('third-party/upstream/tldraw-3.15.6-LICENSE.md'),
    path('dist/public/assets/tldraw/3.15.6/LICENSE.md'),
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) await checkNotices();
  else await writeFile(path('THIRD_PARTY_NOTICES.txt'), await thirdPartyNotices());
}
