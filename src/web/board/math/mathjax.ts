import { mathjax } from 'mathjax-full/js/mathjax.js';
import { TeX } from 'mathjax-full/js/input/tex.js';
import { SVG } from 'mathjax-full/js/output/svg.js';
import { browserAdaptor } from 'mathjax-full/js/adaptors/browserAdaptor.js';
import { RegisterHTMLHandler } from 'mathjax-full/js/handlers/html.js';
import 'mathjax-full/js/input/tex/base/BaseConfiguration.js';
import 'mathjax-full/js/input/tex/ams/AmsConfiguration.js';
import 'mathjax-full/js/input/tex/boldsymbol/BoldsymbolConfiguration.js';
import 'mathjax-full/js/input/tex/braket/BraketConfiguration.js';
import 'mathjax-full/js/input/tex/cancel/CancelConfiguration.js';
import 'mathjax-full/js/input/tex/color/ColorConfiguration.js';
import 'mathjax-full/js/input/tex/mathtools/MathtoolsConfiguration.js';
import 'mathjax-full/js/input/tex/newcommand/NewcommandConfiguration.js';
import 'mathjax-full/js/input/tex/noundefined/NoUndefinedConfiguration.js';
import 'mathjax-full/js/input/tex/physics/PhysicsConfiguration.js';

// Loaded on demand as its own chunk. Only these TeX packages exist: no `html` (\href, \style,
// \class), `require` or `autoload`, so untrusted TeX can neither add markup nor load code.

const adaptor = browserAdaptor();
RegisterHTMLHandler(adaptor);
const input = new TeX({
  packages: [
    'base',
    'ams',
    'boldsymbol',
    'braket',
    'cancel',
    'color',
    'mathtools',
    'newcommand',
    'noundefined',
    'physics',
  ],
});
const output = new SVG({ fontCache: 'local' });
const page = mathjax.document(document, { InputJax: input, OutputJax: output });
document.head.appendChild(output.styleSheet(page) as HTMLStyleElement);

/** TeX source to SVG markup generated by MathJax; errors render as MathJax error nodes. */
export function render(tex: string, display: boolean): string {
  return adaptor.outerHTML(page.convert(tex, { display }) as HTMLElement);
}
